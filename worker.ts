/**
 * Custom Cloudflare Worker entry point.
 *
 * The worker OpenNext generates exports only `fetch`, so a Cron Trigger has no
 * way to reach the application. This re-exports that fetch handler unchanged and
 * adds a `scheduled` handler beside it.
 *
 * The scheduled handler deliberately does NOT import the digest pipeline. It
 * calls the generated fetch handler directly — an in-process function call, not a
 * network request — so the cron path and the manual path run exactly the same
 * code in `/api/cron/digest`, and the application is not bundled twice.
 *
 * Two triggers are configured in wrangler.jsonc:
 *   "0 8 * * 5"    build the week's run and enqueue one job per subscriber
 *   "*\/5 * * * *"  drain the queue, releasing each job when its recipient's
 *                  local morning arrives
 */

// Generated by `opennextjs-cloudflare build`; typed in open-next-worker.d.ts so
// this resolves both before and after a build.
import { default as handler } from "./.open-next/worker.js";

/** Only the bindings this handler itself touches. */
type WorkerEnv = { CRON_SECRET?: string };

const WEEKLY_CRON = "0 8 * * 5";

export default {
  fetch: handler.fetch,

  async scheduled(
    event: ScheduledController,
    env: WorkerEnv,
    ctx: ExecutionContext,
  ) {
    const mode = event.cron === WEEKLY_CRON ? "weekly" : "drain";

    // The hostname is irrelevant — this never leaves the isolate — but it has to
    // be a valid absolute URL for the Request constructor.
    const request = new Request(
      `https://likelylist.internal/api/cron/digest?mode=${mode}`,
      {
        method: "POST",
        headers: { "x-cron-secret": env.CRON_SECRET ?? "" },
      },
    );

    try {
      const response = await handler.fetch(request, env, ctx);
      const body = await response.text();
      // Surfaces in `wrangler tail` and in the dashboard's observability view.
      console.log(`[cron ${event.cron}] ${response.status} ${body.slice(0, 2000)}`);
    } catch (error) {
      console.error(`[cron ${event.cron}] threw`, error);
      // Rethrow so the invocation is recorded as failed rather than silently OK.
      throw error;
    }
  },
} satisfies ExportedHandler<WorkerEnv>;
