/**
 * Custom Cloudflare Worker entry point.
 *
 * The worker OpenNext generates exports only `fetch`, so neither a Cron Trigger nor
 * Email Routing has any way to reach the application. This re-exports that fetch
 * handler unchanged and adds `scheduled` and `email` beside it.
 *
 * Both extra handlers deliberately avoid importing application code. They call the
 * generated fetch handler directly — an in-process function call, not a network
 * request — so every path runs exactly the same route code, and the app is not
 * bundled twice.
 *
 * Cron triggers, configured in wrangler.jsonc:
 *   "0 19 * * 2"    build the week's run and enqueue one job per subscriber
 *   "*\/5 * * * *"  drain the queue, releasing each job when its recipient's
 *                   local Wednesday morning arrives
 *
 * Email routing, configured in the Cloudflare dashboard:
 *   unsubscribe@likelylist.tech  →  send to this Worker
 */

// Generated by `opennextjs-cloudflare build`; typed in open-next-worker.d.ts so
// this resolves both before and after a build.
import { default as handler } from "./.open-next/worker.js";

/** Only the bindings these handlers themselves touch. */
type WorkerEnv = { CRON_SECRET?: string };

const WEEKLY_CRON = "0 19 * * 2";

/**
 * Minimal shape of an inbound message. Declared locally rather than importing
 * Cloudflare's type so this file does not need the generated env types to compile
 * on a clean checkout.
 */
type InboundEmail = {
  readonly from: string;
  readonly to: string;
  readonly headers: Headers;
  setReject(reason: string): void;
};

export default {
  fetch: handler.fetch,

  async scheduled(
    event: ScheduledController,
    env: WorkerEnv,
    ctx: ExecutionContext,
  ) {
    const mode = event.cron === WEEKLY_CRON ? "weekly" : "drain";
    await callInternal(`/api/cron/digest?mode=${mode}`, {}, env, ctx, `cron ${event.cron}`);
  },

  /**
   * A `mailto:` unsubscribe arriving as a real email.
   *
   * Parsed here only as far as the headers — the body is irrelevant, since the
   * account is identified by the subject we set in the List-Unsubscribe header, or
   * failing that by the sender's address. Never rejects the message: bouncing an
   * unsubscribe request is the worst possible outcome.
   */
  async email(message: InboundEmail, env: WorkerEnv, ctx: ExecutionContext) {
    await callInternal(
      "/api/inbound/unsubscribe",
      {
        subject: message.headers.get("subject"),
        from: message.from,
      },
      env,
      ctx,
      "inbound-unsubscribe",
    );
  },
} satisfies ExportedHandler<WorkerEnv>;

/**
 * Calls one of our own routes through the generated fetch handler.
 *
 * The hostname is irrelevant — this never leaves the isolate — but it has to be a
 * valid absolute URL for the Request constructor.
 */
async function callInternal(
  path: string,
  body: Record<string, unknown>,
  env: WorkerEnv,
  ctx: ExecutionContext,
  label: string,
): Promise<void> {
  const request = new Request(`https://likelylist.internal${path}`, {
    method: "POST",
    headers: {
      "x-cron-secret": env.CRON_SECRET ?? "",
      "Content-Type": "application/json",
    },
    body: JSON.stringify(body),
  });

  try {
    const response = await handler.fetch(request, env, ctx);
    const text = await response.text();
    // Surfaces in `wrangler tail` and in the dashboard's observability view.
    console.log(`[${label}] ${response.status} ${text.slice(0, 2000)}`);
  } catch (error) {
    console.error(`[${label}] threw`, error);
    // Rethrown so the invocation is recorded as failed rather than silently OK.
    throw error;
  }
}
